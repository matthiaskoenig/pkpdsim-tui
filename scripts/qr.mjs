/**
 * The QR code of the laboratory, written down as one SVG path.
 *
 * A table has no keyboard and nobody types an address off a screen, so the foot of the landing
 * page carries the address of the laboratory as a square a phone reads. The code never changes,
 * so it is generated here and committed as a module rather than built in the browser: the
 * application carries no QR library, and a table which is offline still shows it.
 *
 *     node scripts/qr.mjs            writes apps/table/src/qr.ts
 *     node scripts/qr.mjs --print    the same, to stdout
 */

import {writeFileSync} from "node:fs";
import {fileURLToPath} from "node:url";
import {dirname, resolve} from "node:path";
import qrcode from "qrcode-generator";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = resolve(ROOT, "apps", "table", "src", "qr.ts");

/** What the square points at: the laboratory, from which everything else is one click. */
const URL_OF_THE_LAB = "https://livermetabolism.com";

/** Medium correction: a quarter of the square may be covered by a hand and it still reads. */
const code = qrcode(0, "M");
code.addData(URL_OF_THE_LAB);
code.make();

const size = code.getModuleCount();
// One path of one square per dark module, in a box of `size` by `size`, so that the drawing
// scales to whatever room the foot of the page has.
const parts = [];
for (let row = 0; row < size; row += 1) {
  for (let column = 0; column < size; column += 1) {
    if (code.isDark(row, column)) parts.push(`M${column} ${row}h1v1h-1z`);
  }
}

const source = `/**
 * The QR code of the laboratory, generated by \`node scripts/qr.mjs\` from
 * ${URL_OF_THE_LAB} and committed, so that the application carries no QR library and a
 * table which is offline still shows it. Do not edit by hand.
 */

/** The address the square points at. */
export const LAB_URL = ${JSON.stringify(URL_OF_THE_LAB)};

/** The width of the code in modules, which is the box the path is drawn in. */
export const LAB_QR_SIZE = ${size};

/** One square per dark module, in a box of ${size} by ${size}. */
export const LAB_QR_PATH = ${JSON.stringify(parts.join(""))};
`;

if (process.argv.includes("--print")) {
  process.stdout.write(`${size} modules, ${parts.length} dark\n`);
} else {
  writeFileSync(OUT, source, "utf8");
  process.stdout.write(`${OUT}: ${size} modules, ${parts.length} dark\n`);
}
