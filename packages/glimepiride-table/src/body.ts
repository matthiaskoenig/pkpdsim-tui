/**
 * Where the drug is: the body of the individual with a bubble on every part of it the model
 * carries, each as big as the amount of glimepiride in that part.
 *
 * The model is a lumped PBPK, so the parts are the ones it has: the gut with the tablet which
 * has not been taken up, the liver, the kidneys, the lungs, the blood and everything else of the
 * body together. The bubbles are measured against the dose which was swallowed, so a visitor
 * sees the drug move from the gut into the body and out of it again rather than a row of
 * numbers which all mean millimoles.
 */

import {attributes, formatNumber, svg} from "@pkpdsim-tui/tui-kit";
import type {Box, Voice} from "@pkpdsim-tui/tui-kit";
import type {Body} from "@pkpdsim-tui/cardio-sim";
import {GLIMEPIRIDE_TEXT} from "./text.ts";

/** One part of the body a bubble stands on. */
export interface Region {
  readonly id: string;
  /** The anchor of the exported body the bubble sits on. */
  readonly organ: string;
  /** The states of the model which are the drug in this part, in millimoles. */
  readonly columns: readonly string[];
  /** Which side of the figure the name is written on. */
  readonly side: "left" | "right";
}

/**
 * A part holds the drug and the two metabolites the liver makes of it, because one molecule of
 * glimepiride becomes one of M1 and then one of M2: counted in millimoles the three of them
 * are the dose which was swallowed, wherever it has got to.
 */
function withMetabolites(columns: readonly string[]): readonly string[] {
  return columns.flatMap(column => [column, column.replace("gli", "m1"), column.replace("gli", "m2")]);
}

/**
 * The parts of the body, in the order the drug passes them. The stomach and the lumen of the
 * gut are the tablet which has not been taken up yet, `LI__gli` is the drug in the hepatocytes,
 * and the blood is the four vessels of the model together.
 */
export const REGIONS: readonly Region[] = [
  {id: "gut", organ: "si",
    // Only the tablet is swallowed, so only it has a stomach to dissolve in.
    columns: ["GU__gli_stomach", ...withMetabolites(["GU__gli_lumen", "Cgu_plasma_gli"])],
    side: "left"},
  {id: "liver", organ: "li", columns: withMetabolites(["LI__gli", "Cli_plasma_gli"]),
    side: "right"},
  {id: "blood", organ: "he",
    columns: withMetabolites(["Cve_gli", "Car_gli", "Cpo_gli", "Chv_gli"]), side: "right"},
  {id: "lung", organ: "lu", columns: withMetabolites(["Clu_gli", "Clu_plasma_gli"]),
    side: "left"},
  {id: "kidney", organ: "ki", columns: withMetabolites(["Cki_plasma_gli"]), side: "left"},
  {id: "rest", organ: "mu", columns: withMetabolites(["Cre_gli", "Cre_plasma_gli"]),
    side: "right"},
  {id: "gone", organ: "go", columns: ["Aurine_m1_m2", "Afeces_gli", "Afeces_m1", "Afeces_m2"],
    side: "right"},
];

/** The radius of the bubble which holds the whole dose, in the centimetres of the figure. */
const BIGGEST = 11;
/** The smallest bubble which is still drawn, as a share of the dose. */
const FAINT = 0.004;

export interface BodyView {
  /** The row of the course to draw, as the columns of the solver carry it. */
  readonly sample: Readonly<Record<string, number>>;
  /** The dose which was swallowed, in millimoles, which every bubble is a share of. */
  readonly dose: number;
}

export interface BodyFigure {
  resize(box: Box): void;
  update(view: BodyView): void;
}

interface Bubble {
  readonly region: Region;
  readonly disc: SVGCircleElement;
  readonly leader: SVGPathElement;
  readonly name: SVGTextElement;
  readonly value: SVGTextElement;
  centre: {x: number; y: number};
}

/** How far apart two names stand, in pixels, so that none of them is read over another. */
const NAME_GAP = 44;
/** How much of each side of the box the names take, in pixels. */
const NAME_COLUMN = 152;

/** What is in one part of the body, in millimoles. */
export function amountIn(
  region: Region, sample: Readonly<Record<string, number>>,
): number {
  return region.columns.reduce((sum, column) => sum + (sample[column] ?? 0), 0);
}

export function createBodyFigure(
  parent: SVGSVGElement, body: Body, voice: Voice,
): BodyFigure {
  const copy = voice.pick(GLIMEPIRIDE_TEXT);
  const root = svg("g", {class: "layer layer--body"}, parent);
  const art = svg("g", {class: "body-art"}, root);
  // The exported body carries its own fills and is generated by pkpdsim, so it goes in as it
  // comes.
  art.innerHTML = body.svg;
  const bubbles: Bubble[] = REGIONS.map(region => ({
    region,
    disc: svg("circle", {class: `drug-bubble drug-bubble--${region.id}`, r: 0}, root),
    leader: svg("path", {class: "drug-leader", d: ""}, root),
    name: svg("text", {class: "drug-name"}, root),
    value: svg("text", {class: "drug-value"}, root),
    centre: {x: 0, y: 0},
  }));

  let layout = {scale: 1, left: 0, top: 0};
  // Where the names stand: a column down each side of the figure, clear of the body itself.
  let columns = {left: 0, right: 0, top: 0, bottom: 0};

  return {
    resize(box: Box): void {
      const scale = box.height / body.height;
      const bounds = art.getBBox();
      const left = box.x + (box.width - bounds.width * scale) / 2 - bounds.x * scale;
      const top = box.y;
      layout = {scale, left, top};
      art.setAttribute("transform", `translate(${left} ${top}) scale(${scale})`);
      // The two columns keep to the edges of the box, so a name never reaches the curve beside
      // the table or the panel behind it.
      columns = {
        left: box.x + NAME_COLUMN,
        right: box.x + box.width - NAME_COLUMN,
        top: box.y + 16, bottom: box.y + box.height - 16,
      };
      for (const bubble of bubbles) {
        const anchor = body.anchors[bubble.region.organ] ?? [0, body.height / 2];
        bubble.centre = {
          x: left + (anchor[0] ?? 0) * scale, y: top + (anchor[1] ?? 0) * scale,
        };
        attributes(bubble.disc, {cx: bubble.centre.x, cy: bubble.centre.y});
      }
    },

    update(view: BodyView): void {
      const dose = view.dose > 0 ? view.dose : 1;
      const shares = new Map<string, number>();
      for (const bubble of bubbles) {
        const share = Math.max(0, amountIn(bubble.region, view.sample) / dose);
        shares.set(bubble.region.id, share);
        // The area of a bubble is what it holds, so the eye compares them the way it compares
        // the volumes they stand for.
        const radius = BIGGEST * Math.sqrt(Math.min(1, share)) * layout.scale;
        bubble.disc.setAttribute("r", radius.toFixed(1));
      }
      // The names stand in a column at each side of the figure rather than beside their
      // bubbles, which in a body lie over one another: the chest alone holds three of them.
      // Each name keeps the height of its own bubble where the column allows it.
      for (const side of ["left", "right"] as const) {
        const column = bubbles
          .filter(bubble => bubble.region.side === side)
          .sort((one, other) => one.centre.y - other.centre.y);
        let last = columns.top;
        for (const bubble of column) {
          const share = shares.get(bubble.region.id) ?? 0;
          const shown = share >= FAINT;
          bubble.name.textContent = shown
            ? copy.regions[bubble.region.id] ?? bubble.region.id
            : "";
          const percent = share * 100;
          bubble.value.textContent = shown
            ? percent < 0.95 ? "< 1 %" : `${formatNumber(percent, 0)} %`
            : "";
          if (!shown) {
            bubble.leader.removeAttribute("d");
            continue;
          }
          const y = Math.min(Math.max(bubble.centre.y, last + NAME_GAP), columns.bottom);
          last = y;
          const x = side === "left" ? columns.left : columns.right;
          const anchor = side === "left" ? "end" : "start";
          attributes(bubble.name, {x, y: y - 3, "text-anchor": anchor});
          attributes(bubble.value, {x, y: y + 16, "text-anchor": anchor});
          // The thread from the name to the bubble it belongs to, which is what keeps the
          // column readable while the bubbles move.
          const to = bubble.centre.x + (side === "left" ? -1 : 1) * 4;
          bubble.leader.setAttribute("d", `M${x} ${y - 7} L${to} ${bubble.centre.y}`);
        }
      }
    },
  };
}
