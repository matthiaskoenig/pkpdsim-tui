/**
 * The anatomy and its circulation. The silhouette and the organ anchors are the ones pkpdsim
 * exports for its physiology figures, so the table and the documentation show the same body.
 * The vessels are a schematic of the pressure network: an aorta, a vena cava, the portal system
 * and the pulmonary circuit, each as wide as the flow it carries.
 */

import type {Body, PressureReference, PressureSolution} from "@pkpdsim-tui/cardio-sim";
import {attributes, line, organRadius, perfusionColor, svg, vesselWidth} from "@pkpdsim-tui/tui-kit";
import type {BeatCycle, BeatFrame} from "./beat.ts";

export interface Viewport {
  readonly width: number;
  readonly height: number;
}

/** The schematic, in the centimetres of the anatomy. */
const AORTA_X = 1.1;
const CAVA_X = -1.5;
const PORTAL_NODE = {x: 4.2, y: 65} as const;
const TRUNK_TOP = 12;
/** The trunks stop at the pelvis; below it the branches run as the iliac vessels do. */
const TRUNK_BOTTOM = 100;
/** The share of the height of the surface the body takes. */
const BODY_SHARE = 0.82;

/**
 * The ventricle on the anatomy, in the centimetres of the body: it empties and fills with the
 * solved course, so the heart on the table beats. The course itself is drawn large at the two
 * long edges, see `pulse.ts`.
 */
const VENTRICLE_RADIUS = 3.1;

/** The side a name is written on, where 1 is to the left of the body as the table sees it. */
const LABEL_SIDE: Readonly<Record<string, number>> = {
  he: 1, si: 1, br: 1, sp: 1, li: -1, ki: -1, mu: -1,
};

interface OrganVisual {
  readonly id: string;
  readonly name: string;
  readonly portal: boolean;
  readonly referenceFlow: number;
  readonly side: number;
  readonly x: number;
  readonly y: number;
  readonly disc: SVGCircleElement;
  readonly supply: SVGPathElement;
  readonly drain: SVGPathElement;
  readonly label: SVGTextElement;
  readonly value: SVGTextElement;
}

/**
 * What the beating heart is doing at this moment of the cycle. The rate and the pressures are
 * written at the edges of the table, so the body itself carries no text of the beat.
 */
export interface BeatView {
  readonly cycle: BeatCycle;
  readonly frame: BeatFrame;
}

export interface Scene {
  resize(viewport: Viewport): void;
  update(solution: PressureSolution, reference: PressureReference): void;
  /** The frame of the beat, or nothing while the heart has not been solved yet. */
  beat(view: BeatView | undefined): void;
}

function anchorOf(body: Body, id: string): {x: number; y: number} | undefined {
  const anchor = body.anchors[id];
  return anchor === undefined ? undefined : {x: anchor[0], y: anchor[1]};
}

export function createScene(parent: SVGSVGElement, body: Body, reference: PressureReference): Scene {
  const root = svg("g", {class: "scene-body"}, parent);
  // The exported body is a set of coloured anatomogram paths, not a single outline, and carries
  // its own fills. It is generated by pkpdsim, so it is inserted as it comes.
  const art = svg("g", {class: "body-art"}, root);
  art.innerHTML = body.svg;

  const drains = svg("g", {class: "layer layer--drains", opacity: 0.55}, root);
  const portals = svg("g", {class: "layer layer--portal"}, root);
  const supplies = svg("g", {class: "layer layer--supply"}, root);
  const discs = svg("g", {class: "layer layer--organs"}, root);
  const labels = svg("g", {class: "layer layer--labels"}, root);

  const aorta = svg("path", {class: "vessel vessel--arterial", d: line(AORTA_X, TRUNK_TOP, AORTA_X, TRUNK_BOTTOM)}, supplies);
  const cava = svg("path", {class: "vessel vessel--venous", d: line(CAVA_X, TRUNK_BOTTOM, CAVA_X, TRUNK_TOP)}, drains);

  const heart = anchorOf(body, "he") ?? {x: 0, y: 44};
  const lungs = anchorOf(body, "lu") ?? {x: -6, y: 42};
  const liver = anchorOf(body, "li") ?? {x: -1.6, y: 56};

  const pulmonaryArtery = svg("path", {
    class: "vessel vessel--venous", d: line(heart.x, heart.y, lungs.x, lungs.y),
  }, drains);
  const pulmonaryVein = svg("path", {
    class: "vessel vessel--arterial", d: line(lungs.x, lungs.y + 1.6, heart.x, heart.y + 1.6),
  }, supplies);
  const lungDisc = svg("circle", {
    class: "organ", cx: lungs.x, cy: lungs.y, r: 3, "fill-opacity": 0.88,
  }, discs);
  const lungLabel = svg("text", {
    class: "organ-label", x: lungs.x, y: lungs.y - 4.2, "text-anchor": "end",
  }, labels);
  lungLabel.textContent = "Lungs";
  const lungValue = svg("text", {
    class: "organ-value", x: lungs.x, y: lungs.y - 1.6, "text-anchor": "end",
  }, labels);

  const portalVein = svg("path", {
    class: "vessel vessel--portal", d: line(PORTAL_NODE.x, PORTAL_NODE.y, liver.x, liver.y),
  }, portals);
  const hepaticVein = svg("path", {
    class: "vessel vessel--venous", d: line(liver.x, liver.y, heart.x, heart.y + 2),
  }, drains);

  const organs: OrganVisual[] = [];
  for (const organ of reference.organs) {
    const anchor = anchorOf(body, organ.id);
    if (anchor === undefined) continue;
    const branchY = Math.min(anchor.y, TRUNK_BOTTOM);
    const supply = svg("path", {
      class: "vessel vessel--arterial", d: line(AORTA_X, branchY, anchor.x, anchor.y),
    }, supplies);
    const drain = organ.portal
      ? svg("path", {
        class: "vessel vessel--portal", d: line(anchor.x, anchor.y, PORTAL_NODE.x, PORTAL_NODE.y),
      }, portals)
      : svg("path", {
        class: "vessel vessel--venous", d: line(anchor.x, anchor.y, CAVA_X, branchY),
      }, drains);
    const disc = svg("circle", {
      class: "organ", cx: anchor.x, cy: anchor.y, r: 2, "fill-opacity": 0.88,
    }, discs);
    // Which way a name reads out of the body. The default follows the midline, but the organs
    // of the upper abdomen sit on top of each other and are placed by hand.
    const side = LABEL_SIDE[organ.id] ?? (anchor.x <= 0 ? -1 : 1);
    const anchorName = side < 0 ? "end" : "start";
    const label = svg("text", {
      class: "organ-label", x: anchor.x, y: anchor.y - 0.4, "text-anchor": anchorName,
    }, labels);
    label.textContent = organ.name;
    const value = svg("text", {
      class: "organ-value", x: anchor.x, y: anchor.y + 2.6, "text-anchor": anchorName,
    }, labels);
    organs.push({
      id: organ.id, name: organ.name, portal: organ.portal, referenceFlow: organ.flow,
      side, x: anchor.x, y: anchor.y, disc, supply, drain, label, value,
    });
  }

  /**
   * Only a few organs are named. The abdomen holds seven of them within a hand's width, and a
   * label on each one would be a wall of text over the anatomy rather than a reading of it.
   */
  const labelled = new Set(["br", "he", "li", "ki", "sp", "si", "mu"]);
  for (const organ of organs) {
    const show = labelled.has(organ.id);
    organ.label.setAttribute("opacity", show ? "1" : "0");
    organ.value.setAttribute("opacity", show ? "1" : "0");
  }

  // The beating heart: the ventricle at the anchor of the heart. The ring is how full it is at
  // its fullest, so the eye sees the disc empty towards it and fill again.
  const beats = svg("g", {class: "layer layer--beat", opacity: 0}, root);
  svg("circle", {class: "ventricle-ring", cx: heart.x, cy: heart.y, r: VENTRICLE_RADIUS}, beats);
  const ventricle = svg("circle", {
    class: "ventricle", cx: heart.x, cy: heart.y, r: VENTRICLE_RADIUS,
  }, beats);
  return {
    resize(viewport: Viewport): void {
      const scale = (viewport.height * BODY_SHARE) / body.height;
      const left = viewport.width / 2;
      const top = (viewport.height - body.height * scale) / 2;
      root.setAttribute("transform", `translate(${left} ${top}) scale(${scale})`);
    },

    update(solution: PressureSolution, referenceState: PressureReference): void {
      const byId = new Map(solution.flows.map(organ => [organ.id, organ]));
      for (const organ of organs) {
        const solved = byId.get(organ.id);
        const flow = solved?.flow ?? 0;
        const ratio = organ.referenceFlow > 0 ? flow / organ.referenceFlow : 1;
        attributes(organ.disc, {r: organRadius(flow), fill: perfusionColor(ratio)});
        attributes(organ.supply, {"stroke-width": vesselWidth(flow)});
        attributes(organ.drain, {"stroke-width": vesselWidth(flow)});
        organ.value.textContent = `${flow.toFixed(2)} l/min`;
        const offset = organ.side * (organRadius(flow) + 1.1);
        organ.label.setAttribute("x", String(organ.x + offset));
        organ.value.setAttribute("x", String(organ.x + offset));
      }
      attributes(aorta, {"stroke-width": vesselWidth(solution.co)});
      attributes(cava, {"stroke-width": vesselWidth(solution.systemicFlow)});
      attributes(portalVein, {"stroke-width": vesselWidth(solution.qpo)});
      attributes(hepaticVein, {"stroke-width": vesselWidth(solution.qh)});
      attributes(pulmonaryArtery, {"stroke-width": vesselWidth(solution.co)});
      attributes(pulmonaryVein, {"stroke-width": vesselWidth(solution.co)});
      attributes(lungDisc, {
        // The pulmonary flow is the whole cardiac output, so it gets a gentler scale than the
        // organs, or it would swallow the heart next to it.
        r: organRadius(solution.co, 1, 1.2, 4.4),
        fill: perfusionColor(solution.co / referenceState.cardiac_output),
      });
      lungValue.textContent = `${solution.co.toFixed(2)} l/min`;
      const lungRadius = organRadius(solution.co, 1, 1.2, 4.4);
      lungValue.setAttribute("y", String(lungs.y - lungRadius - 1.2));
      lungLabel.setAttribute("y", String(lungs.y - lungRadius - 3.8));
    },

    beat(view: BeatView | undefined): void {
      if (view === undefined) {
        beats.setAttribute("opacity", "0");
        return;
      }
      beats.setAttribute("opacity", "1");
      const {cycle, frame} = view;
      // The volume of a ventricle is a volume, so the radius follows its cube root: the disc
      // then grows the way the blood in it does.
      const filled = Math.max(0, Math.min(1, frame.volume / Math.max(cycle.maxVolume, 1e-9)));
      attributes(ventricle, {r: VENTRICLE_RADIUS * Math.cbrt(filled)});
    },
  };
}
